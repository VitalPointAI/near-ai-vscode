#!/usr/bin/env node
// Writes the component catalogue of the documentation site (docs-site/content/architecture/components/) from the compliance fit register
// (compliance/resources.json) and the architecture areas (compliance/architecture-areas.json), with each component's exact pins read by
// compliance/src/inventory.ts. The same inventory feeds the SSP inventory items and the readable CSV of the assessor package, so the three
// cannot disagree. The pages are generated: never edit them by hand. scripts/test/component-catalogue.test.mjs fails when the committed
// pages differ from what the register renders, the way the capacity page is checked.
//
//   node scripts/build-component-catalogue.mjs           write the pages (and remove a generated page whose area has gone)
//   node scripts/build-component-catalogue.mjs --check   write nothing; exit 1 when a page is missing, extra or different
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadInventory, pinText } from '../compliance/src/inventory.ts';

export const CATALOGUE_DIR = 'docs-site/content/architecture/components';
export const GENERATED_MARK = '<!-- Generated by scripts/build-component-catalogue.mjs from compliance/resources.json and compliance/architecture-areas.json. Do not edit: change those files and run node scripts/build-component-catalogue.mjs. -->';

const KIND_ORDER = ['vendored', 'npm', 'image', 'chart', 'tool', 'action', 'model'];
const KINDS = {
  vendored: 'Library shipped inside the extension (vendored)',
  npm: 'npm package',
  image: 'Container image',
  chart: 'Helm chart',
  tool: 'Pinned tool',
  action: 'GitHub Action',
  model: 'Model (shipped passport)'
};
const SCOPES = { runtime: 'Runtime: it runs in the product', build: 'Build only: not shipped', test: 'Test only: not shipped' };
const FITS = { pass: 'Pass', 'pass-with-conditions': 'Pass with conditions', fail: 'Fail' };

/** Markdown-safe text: characters that would start emphasis, code, links, HTML or a table cell are escaped. */
export const md = (value) => String(value ?? '').replace(/[\\`*_[\]<>|]/g, (char) => `\\${char}`).replace(/\r?\n/g, ' ');
const code = (value) => `\`${String(value).replaceAll('`', "'")}\``;

/** sa-15 as SA-15, cm-08.01 as CM-8(1); any other id upper-cased as it is. */
export function controlLabel(id) {
  const match = /^([a-z]{2})-0*(\d+)(?:\.0*(\d+))?$/.exec(id);
  if (!match) return id.toUpperCase();
  return `${match[1].toUpperCase()}-${match[2]}${match[3] ? `(${match[3]})` : ''}`;
}

const cryptoText = (value) => {
  if (value === 'none') return 'None';
  if (value === 'uses-platform') return "Uses the platform's cryptography";
  if (value === 'unvalidated') return 'Not a validated cryptographic module';
  return value.startsWith('validated:') ? `Validated: ${value.slice('validated:'.length)}` : value;
};
const airGapText = (value) => {
  if (value === 'ok') return 'Works with no internet access';
  if (value === 'no') return 'Needs the internet: does not work air-gapped';
  return value.startsWith('needs-mirror:') ? `Works air-gapped once mirrored: ${value.slice('needs-mirror:'.length)}` : value;
};

const sortEntries = (entries) => [...entries].sort((a, b) => KIND_ORDER.indexOf(a.kind) - KIND_ORDER.indexOf(b.kind) || a.name.localeCompare(b.name) || a.id.localeCompare(b.id));

/** One component's section on its area page. */
function renderEntry(entry) {
  const pins = entry.pins.length > 1
    ? entry.pins.map(({ pin, where }) => `${code(pin)} in ${where.map(code).join(', ')}`).join('; ')
    : entry.pins.length ? code(entry.pins[0].pin) : 'Not pinned in a lock or manifest';
  const rows = [
    ['Kind', md(KINDS[entry.kind] ?? entry.kind)],
    ['Pinned version or digest', pins],
    ['Architecture component', code(entry.component)],
    ['Used in', entry.where.map(code).join(', ')],
    ['Scope', md(SCOPES[entry.scope] ?? entry.scope)],
    ['Licence', md(entry.licence)],
    ['Cryptography', md(cryptoText(entry.crypto))],
    ['Air gap', md(airGapText(entry.airGap))],
    ['Compliance fit', md(FITS[entry.fit] ?? entry.fit)],
    ['Controls', md(entry.controls.map(controlLabel).join(', '))],
    ['Security fixes', md(entry.cveResponse)],
    ['Reviewed', md(`${entry.reviewer}, ${entry.reviewedAt}`)]
  ];
  const lines = [
    `## ${md(entry.id)}`,
    '',
    `**What it provides.** ${md(entry.purpose)}`,
    '',
    `**Why it is needed.** ${md(entry.role)}${entry.roleNeedsReview ? ' *This role is waiting for the owner to confirm it.*' : ''}`,
    '',
    '| | |',
    '| --- | --- |',
    ...rows.map(([label, value]) => `| ${label} | ${value} |`),
    ''
  ];
  if (entry.conditions.length) lines.push('Conditions:', '', ...entry.conditions.map((condition) => `- ${md(condition)}`), '');
  return lines.join('\n');
}

const front = (label, position) => `---\nsidebar_label: ${JSON.stringify(label)}\nsidebar_position: ${position}\n---\n\n${GENERATED_MARK}\n\n`;

function renderArea(area, entries, position) {
  const sorted = sortEntries(entries);
  const table = ['| Component | Kind | Scope | Fit |', '| --- | --- | --- | --- |',
    ...sorted.map((entry) => `| ${md(entry.id)} | ${md(KINDS[entry.kind] ?? entry.kind)} | ${md(entry.scope)} | ${md(FITS[entry.fit] ?? entry.fit)} |`)];
  return `${front(area.title, position)}# ${md(area.title)}\n\n${md(area.summary)}\n\nBack to the [component catalogue](./index.md).\n\n${table.join('\n')}\n\n${sorted.map(renderEntry).join('\n')}`;
}

function renderIndex(inventory, used, repoUrl) {
  const review = inventory.entries.filter((entry) => entry.roleNeedsReview).length;
  const lines = [
    `${front('Overview', 1)}# Component catalogue`,
    '',
    'This catalogue lists every third-party component the product is built from or runs on: the packages, libraries, container images, Helm charts, tools and GitHub Actions. For each one it says what the component provides, why the architecture needs it, the exact version or digest that is pinned, where it is used, and how it fits the compliance requirements.',
    '',
    'Nothing here is typed by hand. The pages are generated from the compliance fit register, [`compliance/resources.json`](' + `${repoUrl}/blob/main/compliance/resources.json` + '), which CI checks against what the repository really uses. A component cannot be added without a reviewed entry, and an entry cannot stay after the component is removed. The same register produces the component inventory in the assessor package.',
    '',
    'This catalogue is evidence for these controls in the compliance package: CM-8 and CM-8(1) (the inventory, kept current with each change), CM-7 (why each component is needed), SA-4 (the review before a component is used), SA-5 (this documentation) and SR-3 (exact pins). It is evidence only: your organization decides what it accepts.',
    '',
    `There are ${inventory.entries.length} components in ${used.length} areas. ${review ? `The role of ${review} of them is waiting for the owner to confirm it; each says so.` : 'Every role has been confirmed.'}`,
    '',
    '## How to read an entry',
    '',
    '- **Scope** says whether the component runs in the product (runtime), or is only used to build or test it.',
    '- **Compliance fit** is the register\'s verdict. "Pass with conditions" means the component may be used only as its conditions say; they are listed under the entry.',
    '- **Air gap** says whether it works with no internet access. Software for a hosted site always arrives as a signed offline bundle.',
    '- **Controls** are the controls the component helps with or affects.',
    '',
    '## Areas',
    ''
  ];
  for (const { area, entries } of used) {
    lines.push(`### [${md(area.title)}](./${area.id}.md)`, '', md(area.summary), '', `${entries.length} component${entries.length === 1 ? '' : 's'}: ${sortEntries(entries).map((entry) => md(entry.id)).join(', ')}.`, '');
  }
  lines.push(
    '## Software bill of materials',
    '',
    'This catalogue covers the direct components that someone chose and reviewed. A software bill of materials (SBOM) is the machine-readable list of everything inside a shipped file, including every package those components pull in. Use the catalogue to understand why each part is there; use the SBOM to check exactly what a release contains.',
    '',
    'Each release keeps its SBOMs with the release itself, in CycloneDX JSON:',
    '',
    '- **The extension package (VSIX)** carries `extension/sbom.cdx.json`: every third-party package the extension ships, and the bundled map data. The release workflow builds it with the package.',
    '- **The assessor package** (`compliance-package-<version>.tar.gz` on the GitHub release) carries the same file as `evidence/bundle/vsix-sbom.cdx.json`, and the relay image SBOM that Syft writes as `evidence/relay-image-sbom.json`.',
    '- **The images we rebuild for a hosted site** each get a Syft SBOM. When an image is published from a release tag, its SBOM is attached to it as a signed GitHub attestation.',
    '- **The workbench image** has no SBOM of its own yet. It is planned with the Phase 46 work that also signs that image.',
    '',
    'To get the SBOMs of one release, for example version 0.4.38, with the [GitHub CLI](https://cli.github.com/):',
    '',
    '```sh',
    `gh release download v0.4.38 --repo ${repoUrl.replace('https://github.com/', '')} --pattern '*.vsix' --pattern '*.vsix.sha256' --pattern 'compliance-package-*'`,
    'sha256sum --check near-ai-vscode-0.4.38.vsix.sha256',
    'sha256sum --check compliance-package-0.4.38.tar.gz.sha256',
    'unzip -p near-ai-vscode-0.4.38.vsix extension/sbom.cdx.json > extension-sbom.cdx.json',
    'tar -xzf compliance-package-0.4.38.tar.gz',
    '```',
    '',
    `To check the SBOM attestation of a rebuilt image, use its digest from the release: \`gh attestation verify oci://<image>@<digest> --repo ${repoUrl.replace('https://github.com/', '')} --predicate-type https://cyclonedx.org/bom\`.`,
    '',
    'The catalogue on this site shows the register as it is on `main`. The register as it was for a given release is in that release\'s source. Releases made after this catalogue was added also carry it in their assessor package, as `readable/component-inventory.csv` and as inventory items in each system security plan.',
    ''
  );
  return lines.join('\n');
}

/** Every generated page, by path relative to the repository root. */
export function renderCatalogue(root) {
  const inventory = loadInventory(root);
  const manifest = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8'));
  const repoUrl = String(manifest.repository?.url ?? manifest.repository ?? '').replace(/^git\+/, '').replace(/\.git$/, '');
  if (!/^https:\/\/github\.com\/[^/]+\/[^/]+$/.test(repoUrl)) throw new Error(`The root package.json repository URL is not a GitHub URL: ${repoUrl}`);
  const known = new Set(inventory.areas.map((area) => area.id));
  const stray = inventory.entries.filter((entry) => !known.has(entry.architectureArea));
  if (stray.length) throw new Error(`Entries name an unknown architecture area: ${stray.map((entry) => entry.id).join(', ')}`);
  const used = inventory.areas.map((area) => ({ area, entries: inventory.entries.filter((entry) => entry.architectureArea === area.id) })).filter(({ entries }) => entries.length);
  const pages = new Map([[`${CATALOGUE_DIR}/index.md`, renderIndex(inventory, used, repoUrl)]]);
  used.forEach(({ area, entries }, index) => pages.set(`${CATALOGUE_DIR}/${area.id}.md`, renderArea(area, entries, index + 2)));
  return pages;
}

/** The pages in the catalogue folder that differ from what the register renders, are missing, or are left over. */
export function checkCatalogue(root) {
  const pages = renderCatalogue(root);
  const problems = [];
  for (const [file, text] of pages) {
    const full = path.join(root, file);
    if (!existsSync(full)) problems.push(`${file} is missing; run node scripts/build-component-catalogue.mjs.`);
    else if (readFileSync(full, 'utf8') !== text) problems.push(`${file} differs from compliance/resources.json; run node scripts/build-component-catalogue.mjs and commit the result.`);
  }
  const dir = path.join(root, CATALOGUE_DIR);
  if (existsSync(dir)) for (const name of readdirSync(dir).sort()) {
    if (!pages.has(`${CATALOGUE_DIR}/${name}`)) problems.push(`${CATALOGUE_DIR}/${name} is not a generated catalogue page; remove it (the folder holds generated pages only).`);
  }
  return problems;
}

export function main(argv = process.argv.slice(2), root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')) {
  if (argv.includes('--check')) {
    const problems = checkCatalogue(root);
    for (const problem of problems) process.stderr.write(`${problem}\n`);
    if (!problems.length) process.stdout.write('The component catalogue matches compliance/resources.json.\n');
    return problems.length ? 1 : 0;
  }
  const pages = renderCatalogue(root);
  const dir = path.join(root, CATALOGUE_DIR);
  mkdirSync(dir, { recursive: true });
  for (const name of readdirSync(dir)) {
    const file = path.join(dir, name);
    if (!pages.has(`${CATALOGUE_DIR}/${name}`) && name.endsWith('.md') && readFileSync(file, 'utf8').includes(GENERATED_MARK)) rmSync(file);
  }
  for (const [file, text] of pages) writeFileSync(path.join(root, file), text);
  process.stdout.write(`Wrote ${pages.size} component catalogue pages to ${CATALOGUE_DIR}.\n`);
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main();
