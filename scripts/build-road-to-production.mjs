#!/usr/bin/env node
// Writes docs-site/content/security/road-to-production.md from the gap register (compliance/gaps.json) and its POA&M items
// (compliance/poam/), grouped by the lowest level where each gap matters (appliesAt) and then by whether it blocks production
// (blocksProduction). The levels and their order come from compliance/schemas/gaps.schema.json, the one place they are defined.
// The page is generated: never edit it by hand. docs-site/test/roadToProduction.test.mjs, in the required docs job, fails when the
// committed page differs from what the register renders, the way the component catalogue is checked.
//
// The same check keeps the register current: a phase SUMMARY's "## Open conditions" section must cite a gap id that exists in the
// register for each open condition, or say "None.". SUMMARY files completed on or after OPEN_CONDITIONS_FROM must have that section.
//
//   node scripts/build-road-to-production.mjs           write the page
//   node scripts/build-road-to-production.mjs --check   write nothing; exit 1 when the page differs, or the register or a SUMMARY breaks a rule
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { controlLabel, md } from './build-component-catalogue.mjs';

export const PAGE = 'docs-site/content/security/road-to-production.md';
export const GENERATED_MARK = '<!-- Generated by scripts/build-road-to-production.mjs from compliance/gaps.json and compliance/poam/. Do not edit: change the register and run node scripts/build-road-to-production.mjs. -->';
/** SUMMARY files completed on or after this day must say what open conditions they found (the rule in .planning/PROJECT.md). */
export const OPEN_CONDITIONS_FROM = '2026-11-25';

/** How each level reads on the page. Every level in the schema needs one, and nothing else may have one. */
const LEVEL_TEXT = {
  now: ['Now, at every level', 'These matter today, at every level, including unclassified work.'],
  'protected-a': ['From Protected A', 'These matter once your organization holds Protected A information.'],
  'protected-b': ['From Protected B', 'These matter from Protected B, where validated cryptography and hardened base images are expected.'],
  'protected-c': ['From Protected C', 'These matter from Protected C.'],
  confidential: ['From Confidential', 'These matter once a site holds classified information, starting at Confidential.'],
  secret: ['From Secret', 'These matter from Secret.'],
  'top-secret': ['From Top Secret', 'These matter from Top Secret.'],
  'coalition-exchange': ['For exchange with allies', 'These matter when your organization exchanges labelled objects with allied partners. Here, an item that blocks production blocks live exchange with allies.']
};
const OWNER_ROLES = new Set(['maintainers', 'release-owner', 'owner', 'shared']);
const GAP_ID = /\b[GX][0-9]+\b/g;

const readJson = (file) => JSON.parse(readFileSync(file, 'utf8'));
const idOrder = (a, b) => a.id[0].localeCompare(b.id[0]) || Number(a.id.slice(1)) - Number(b.id.slice(1));

/** The levels, lowest first, from the register's schema. */
export function loadLevels(root) {
  const levels = readJson(path.join(root, 'compliance/schemas/gaps.schema.json')).definitions?.appliesAt?.enum;
  if (!Array.isArray(levels) || levels.length === 0) throw new Error('compliance/schemas/gaps.schema.json defines no appliesAt levels');
  const missing = levels.filter((level) => !LEVEL_TEXT[level]);
  const extra = Object.keys(LEVEL_TEXT).filter((level) => !levels.includes(level));
  if (missing.length || extra.length) throw new Error(`The page's level texts do not match the schema's appliesAt list (missing: ${missing.join(', ') || 'none'}; extra: ${extra.join(', ') || 'none'})`);
  return levels;
}

/** Problems with the fields this page depends on. It fails closed: a missing or unknown value is a problem, never a default. */
export function registerProblems(gaps, levels, poam) {
  const problems = [];
  const seen = new Set();
  gaps.forEach((gap, index) => {
    const at = typeof gap?.id === 'string' ? gap.id : `entry ${index}`;
    if (typeof gap?.id !== 'string' || !/^[GX][0-9]+$/.test(gap.id)) problems.push(`${at}: the id is missing or malformed`);
    else if (seen.has(gap.id)) problems.push(`${at}: the id is used twice`);
    seen.add(gap?.id);
    for (const field of ['title', 'remediation']) if (typeof gap?.[field] !== 'string' || gap[field].trim() === '') problems.push(`${at}: ${field} is missing`);
    if (!Array.isArray(gap?.controls) || gap.controls.length === 0) problems.push(`${at}: controls are missing`);
    if (!OWNER_ROLES.has(gap?.ownerRole)) problems.push(`${at}: ownerRole is missing or unknown`);
    if (!levels.includes(gap?.appliesAt)) problems.push(`${at}: appliesAt is missing or not one of ${levels.join(', ')}`);
    if (typeof gap?.blocksProduction !== 'boolean') problems.push(`${at}: blocksProduction is missing or not true or false`);
    if ((gap?.closesInPhase === undefined) === (gap?.poam === undefined)) problems.push(`${at}: needs exactly one of closesInPhase and poam`);
    if (gap?.poam !== undefined && !poam.has(gap.poam)) problems.push(`${at}: POA&M item ${gap.poam} does not exist`);
  });
  return problems;
}

function loadPoamItems(root) {
  const dir = path.join(root, 'compliance/poam');
  const items = new Map();
  if (!existsSync(dir)) return items;
  for (const name of readdirSync(dir).sort()) {
    if (!name.endsWith('.json')) continue;
    const item = readJson(path.join(dir, name));
    items.set(item.id, item);
  }
  return items;
}

/** The register, checked. Throws with every problem when an entry lacks a field the page needs. */
export function loadRegister(root) {
  const levels = loadLevels(root);
  const gaps = readJson(path.join(root, 'compliance/gaps.json')).gaps;
  if (!Array.isArray(gaps) || gaps.length === 0) throw new Error('compliance/gaps.json has no gaps');
  const poam = loadPoamItems(root);
  const problems = registerProblems(gaps, levels, poam);
  if (problems.length) throw new Error(`compliance/gaps.json:\n${problems.join('\n')}`);
  return { levels, gaps, poam };
}

function whereItCloses(gap, poam) {
  if (gap.closesInPhase !== undefined) return `Planned in Phase ${md(gap.closesInPhase)}.`;
  const first = poam.get(gap.poam)?.milestones?.[0];
  const when = first?.phase ? `Phase ${md(first.phase)}` : first?.targetDate ? `by ${md(first.targetDate)}` : '';
  return `Tracked as POA&M item ${md(gap.poam)}${first ? `; first milestone: ${md(first.title)}${when ? ` (${when})` : ''}` : ''}.`;
}

const entryLine = (gap, poam) => `- **${md(gap.id)}. ${md(gap.title)}.** ${md(gap.remediation)} Controls: ${md(gap.controls.map(controlLabel).join(', '))}. Owner role: ${md(gap.ownerRole)}. ${whereItCloses(gap, poam)}`;

/** The page, from the register. */
export function renderRoadToProduction(root) {
  const { levels, gaps, poam } = loadRegister(root);
  const sorted = [...gaps].sort(idOrder);
  const inLevel = (level, blocks) => sorted.filter((gap) => gap.appliesAt === level && gap.blocksProduction === blocks);
  const blocking = sorted.filter((gap) => gap.blocksProduction).length;
  const lines = [
    '---',
    'sidebar_label: "Road to production"',
    'sidebar_position: 2',
    '---',
    '',
    GENERATED_MARK,
    '',
    '# Road to production and higher classification',
    '',
    'This page lists every known gap and open condition: what is still to do before live use, and what changes as your organization moves to a higher classification level. It is one list, kept in the gap register, so nothing found during planning or building is lost.',
    '',
    'Each item is listed once, at the lowest level where it matters. It still matters at every level above that. Items for exchange with allies are listed on their own, because that work can start at any level.',
    '',
    `Production means live use for real work at your organization's site. An item that blocks production must be closed, or accepted by your organization's authorizing official, before that. An item that does not block production still matters at its level. Where the right level or the effect on production was not clear, the register uses the stricter value. Of the ${sorted.length} items, ${blocking} block production.`,
    '',
    'This page shows the register, not progress. Some items may already be closed by evidence. The [gaps page](../accreditation/gaps.mdx) shows the current state of each one. Your organization decides what it accepts.',
    '',
    '## How this list stays current',
    '',
    'The list is generated from the gap register, [`compliance/gaps.json`](https://github.com/VitalPointAI/near-ai-vscode/blob/main/compliance/gaps.json), and its POA&M items. The same register feeds the POA&M, the accreditation pages and the assessor package. Each item names the lowest level where it matters (`appliesAt`) and whether it blocks production (`blocksProduction`); an item without both is refused. Any open condition found while planning or building a phase is added to the register before the phase closes, and the phase summary cites its id. CI fails when this page differs from the register, or when a phase summary lists an open condition without a gap id.',
    '',
    '## Summary',
    '',
    '| Level | Blocks production | Does not block production |',
    '| --- | --- | --- |',
    ...levels.map((level) => `| [${LEVEL_TEXT[level][0]}](#${level}) | ${inLevel(level, true).length} | ${inLevel(level, false).length} |`),
    ''
  ];
  for (const level of levels) {
    const [title, text] = LEVEL_TEXT[level];
    lines.push(`## ${title} {#${level}}`, '', text, '');
    const blocks = inLevel(level, true); const other = inLevel(level, false);
    if (!blocks.length && !other.length) { lines.push('Nothing is recorded at this level yet.', ''); continue; }
    for (const [heading, list] of [['Blocks production', blocks], ['Does not block production', other]]) {
      if (!list.length) continue;
      lines.push(`### ${heading} {#${level}-${heading === 'Blocks production' ? 'blocks' : 'does-not-block'}}`, '', ...list.map((gap) => entryLine(gap, poam)), '');
    }
  }
  return lines.join('\n');
}

/** The front matter's completed date of a SUMMARY file, if it has one. */
function completedOn(text) {
  const front = /^---\n([\s\S]*?)\n---/.exec(text)?.[1] ?? '';
  return /^completed:\s*['"]?([0-9]{4}-[0-9]{2}-[0-9]{2})/m.exec(front)?.[1];
}

/** The lines of a "## Open conditions" section, or undefined when the file has none. */
function openConditionsSection(text) {
  const lines = text.split(/\r?\n/);
  const start = lines.findIndex((line) => /^## Open conditions\s*$/.test(line));
  if (start < 0) return undefined;
  const end = lines.findIndex((line, index) => index > start && /^#{1,2} /.test(line));
  return lines.slice(start + 1, end < 0 ? undefined : end).filter((line) => line.trim() !== '');
}

/** Problems with the "## Open conditions" sections of the phase SUMMARY files. */
export function summaryProblems(root, gapIds) {
  const problems = [];
  const phases = path.join(root, '.planning/phases');
  if (!existsSync(phases)) return problems;
  for (const dir of readdirSync(phases).sort()) {
    const full = path.join(phases, dir);
    if (!statSync(full).isDirectory()) continue;
    for (const name of readdirSync(full).sort().filter((file) => file.endsWith('-SUMMARY.md'))) {
      const file = `.planning/phases/${dir}/${name}`;
      const text = readFileSync(path.join(full, name), 'utf8');
      const section = openConditionsSection(text);
      const completed = completedOn(text);
      if (section === undefined) {
        if (completed !== undefined && completed >= OPEN_CONDITIONS_FROM) problems.push(`${file}: completed ${completed} with no "## Open conditions" section; list each open condition with its gap id, or write "None."`);
        continue;
      }
      if (section.length === 1 && section[0].trim() === 'None.') continue;
      if (section.length === 0) { problems.push(`${file}: the "## Open conditions" section is empty; write "None." or list each condition with its gap id`); continue; }
      for (const line of section) {
        if (!/^\s*[-*] /.test(line)) { problems.push(`${file}: "${line.trim()}" in "## Open conditions" is not a list item; write "None." or one item per condition`); continue; }
        const ids = line.match(GAP_ID) ?? [];
        if (ids.length === 0) problems.push(`${file}: "${line.trim()}" names no gap id; add the condition to compliance/gaps.json and cite its id`);
        for (const id of ids) if (!gapIds.has(id)) problems.push(`${file}: gap ${id} is not in compliance/gaps.json`);
      }
    }
  }
  return problems;
}

/** Every problem: the page against the register, the register's own fields, and the SUMMARY sections. */
export function checkRoadToProduction(root) {
  let page;
  try { page = renderRoadToProduction(root); } catch (error) { return [error.message]; }
  const problems = [];
  const full = path.join(root, PAGE);
  if (!existsSync(full)) problems.push(`${PAGE} is missing; run node scripts/build-road-to-production.mjs.`);
  else if (readFileSync(full, 'utf8') !== page) problems.push(`${PAGE} differs from compliance/gaps.json; run node scripts/build-road-to-production.mjs and commit the result.`);
  const ids = new Set(readJson(path.join(root, 'compliance/gaps.json')).gaps.map((gap) => gap.id));
  return [...problems, ...summaryProblems(root, ids)];
}

export function main(argv = process.argv.slice(2), root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')) {
  if (argv.includes('--check')) {
    const problems = checkRoadToProduction(root);
    for (const problem of problems) process.stderr.write(`${problem}\n`);
    if (!problems.length) process.stdout.write('The road to production page matches compliance/gaps.json, and every SUMMARY cites its open conditions.\n');
    return problems.length ? 1 : 0;
  }
  writeFileSync(path.join(root, PAGE), renderRoadToProduction(root));
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main();
