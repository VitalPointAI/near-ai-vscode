#!/usr/bin/env node
// Builds deploy/tools/credential-checker.engine.mjs (Phase 71 plan 08): one self-contained ES module made with the existing esbuild devDependency from
// the product's own credential code in src/domain/, so credential-check.mjs checks with exactly the checker the extension, the hub and the fold use.
// The engine is generated, never committed (.gitignore), and deploy/bundle/build.mjs makes it before it packs deploy/, so it travels to operators in
// the signed offline bundle and an air-gapped machine needs no compile and no checkout. Its only imports are node: built-ins.
//
//   node deploy/tools/build-credential-engine.mjs
//
// Exit codes: 0 built, 1 failed (one sentence on stderr).
import { build } from 'esbuild';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..');
export const ENGINE_FILE = path.join(HERE, 'credential-checker.engine.mjs');

// What the engine exposes: the checker, and the builders the tests and the issuer tool make fixtures and files with.
const EXPORTS = [
  ['src/domain/credentials/profile.ts', ['verifyCredential', 'readCredential', 'credentialHash', 'issueCredential']],
  ['src/domain/credentials/evidence.ts', ['checkEvidence']],
  ['src/domain/credentials/statusList.ts', ['verifyStatusList', 'statusAt', 'listHash', 'buildStatusList', 'signStatusList']],
  ['src/domain/credentials/issuerAuthority.ts', ['issuerAuthority']],
  ['src/domain/credentials/multibase.ts', ['encodePublicKeyMultibase', 'decodePublicKeyMultibase']],
  ['src/domain/did/didWebvh.ts', ['verifyWebvhLog', 'buildGenesisEntry']],
  ['src/domain/gate/enrolment.ts', ['verifyOrganizationLayer', 'buildOrganizationLayer']],
  ['src/domain/gate/bundle.ts', ['defaultBundlePayload']],
  ['src/domain/gate/policyDocument.ts', ['documentFromBundle']],
  ['src/domain/team/canonical.ts', ['fingerprintOf']]
];

/** Builds the engine at `out` (the default beside this tool). Throws when esbuild fails or the result imports anything but node: built-ins. */
export async function buildCredentialEngine(root = ROOT, out = ENGINE_FILE) {
  for (const [file] of EXPORTS) if (!existsSync(path.join(root, file))) throw new Error(`The credential code is missing: ${file}.`);
  const contents = EXPORTS.map(([file, names]) => `export { ${names.join(', ')} } from ${JSON.stringify(path.join(root, file))};`).join('\n');
  const result = await build({
    stdin: { contents, resolveDir: root, sourcefile: 'credential-checker.entry.ts', loader: 'ts' },
    bundle: true, platform: 'node', format: 'esm', target: 'node22', outfile: out, write: true, metafile: true, logLevel: 'silent',
    banner: { js: '// Generated by deploy/tools/build-credential-engine.mjs from src/domain/. Do not edit; do not commit.' }
  });
  const outside = Object.values(result.metafile.outputs).flatMap((output) => output.imports).filter((entry) => entry.external && !entry.path.startsWith('node:'));
  if (outside.length > 0) throw new Error(`The engine imports something outside Node's built-ins: ${outside.map((entry) => entry.path).join(', ')}.`);
  return out;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const out = await buildCredentialEngine();
    console.log(`Built ${path.relative(ROOT, out)}.`);
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(1);
  }
}
